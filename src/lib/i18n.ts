import { create } from "zustand";

export type Lang = "zh" | "en";

const STORAGE_KEY = "museek.lang";

/** Pick the initial language: a previously saved choice wins, otherwise fall
 *  back to the system locale (Chinese when it starts with "zh", else English). */
function detectInitialLang(): Lang {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (saved === "zh" || saved === "en") return saved;
  return (navigator.language || "").toLowerCase().startsWith("zh")
    ? "zh"
    : "en";
}

interface LangState {
  lang: Lang;
  setLang: (l: Lang) => void;
}

export const useLangStore = create<LangState>((set) => ({
  lang: detectInitialLang(),
  setLang(lang) {
    localStorage.setItem(STORAGE_KEY, lang);
    set({ lang });
    void syncWindowTitle(lang);
  },
}));

/** Apply a language received from the main window without writing local prefs. */
export function applyLanguageSnapshot(lang: Lang): void {
  useLangStore.setState({ lang });
  void syncWindowTitle(lang);
}

const isTauri =
  typeof window !== "undefined" && "__TAURI_INTERNALS__" in window;

/** Keep the OS window / taskbar title in sync with the UI language. */
export async function syncWindowTitle(lang?: Lang): Promise<void> {
  const resolved = lang ?? useLangStore.getState().lang;
  const title = translate(resolved, "app.name");
  if (typeof document !== "undefined") document.title = title;
  if (!isTauri) return;
  try {
    const { getCurrentWindow } = await import("@tauri-apps/api/window");
    await getCurrentWindow().setTitle(title);
  } catch {
    /* optional */
  }
}

